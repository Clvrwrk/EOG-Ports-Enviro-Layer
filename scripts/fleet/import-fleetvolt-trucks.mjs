#!/usr/bin/env node
/**
 * Rebuild src/portos/fleet/fleetvoltTrucks.js from FleetVolt's truck files.
 *
 * Usage:
 *   git clone https://github.com/Clvrwrk/fleetvolt.git /tmp/fleetvolt
 *   node scripts/fleet/import-fleetvolt-trucks.mjs /tmp/fleetvolt/data/trucks
 *   npx prettier --write src/portos/fleet/fleetvoltTrucks.js
 *
 * Keeps the physics parameters, charge curve, street efficiency, battery
 * guidance, HVIP eligibility and CARB check of every truck; drops the HVIP
 * dealer lists. Ids are the FleetVolt file names (stable: the catalog, saved
 * plans and the freight footprint key on them).
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = process.argv[2];
if (!dir) {
  console.error('usage: import-fleetvolt-trucks.mjs <fleetvolt>/data/trucks');
  process.exit(1);
}
const OUT = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../../src/portos/fleet/fleetvoltTrucks.js',
);

const PHYSICS = [
  'nameplate_kwh',
  'usable_kwh',
  'bms_reserve_kwh',
  'curb_weight_lbs',
  'drag_coefficient',
  'frontal_area_m2',
  'C_rr',
  'regen_efficiency',
  'aux_kw_base',
  'drivetrain_efficiency',
];

const trucks = readdirSync(dir)
  .filter((f) => f.endsWith('.json'))
  .sort()
  .map((file) => {
    const raw = JSON.parse(readFileSync(join(dir, file), 'utf8'));
    const street = raw.street_metadata ?? {};
    const physics = Object.fromEntries(PHYSICS.map((k) => [k, raw[k]]));
    physics.charge_curve = raw.charge_curve ?? [];
    return {
      id: basename(file, '.json'),
      name: raw.name,
      physics,
      street: {
        vehicleClass: street.vehicleClass ?? 8,
        axleConfig: street.axleConfig ?? null,
        chemistry: street.batteryChemistry ?? null,
        kwhPerMi: street.streetEfficiencyKwhPerMi ?? null,
        rangeMi: street.ratedRangeMiles ?? null,
        recommendedMilesPerCharge: street.recommendedMilesPerCharge ?? null,
        batteryGuidance: street.batteryHealthGuidance ?? null,
        sources: street.streetDataSources ?? [],
        confidence: street.streetDataConfidence ?? 'low',
      },
      hvip: raw.hvip
        ? {
            eligible: Boolean(raw.hvip.eligible),
            incentive: raw.hvip.incentiveAmount ?? null,
            category: raw.hvip.category ?? null,
            vehicleType: raw.hvip.vehicleType ?? null,
            modelYear: raw.hvip.modelYear ?? null,
            url: raw.hvip.url ?? null,
            batteryOptions: raw.hvip.batteryOptions ?? [],
          }
        : null,
      carb: raw.carbValidation?.derivedKwhPerMi
        ? {
            kwhPerMi: raw.carbValidation.derivedKwhPerMi,
            source: raw.carbValidation.source,
          }
        : null,
      notes: raw.source_notes ?? '',
    };
  });

const body = `/**
 * Battery-electric Class 8 trucks from FleetVolt's truck library
 * (github.com/Clvrwrk/fleetvolt, data/trucks). Generated by
 * scripts/fleet/import-fleetvolt-trucks.mjs; edit the source files and
 * re-run rather than editing here.
 *
 * physics: FleetVolt simulator parameters (see ./physics.js truckParams)
 * street: in-service efficiency band (kWh/mi), range and battery guidance
 * hvip: California HVIP voucher eligibility; carb: CARB 2018 drayage check
 */
export const FLEETVOLT_TRUCKS = Object.freeze(${JSON.stringify(trucks, null, 2)});
`;
writeFileSync(OUT, body);
console.log(`wrote ${trucks.length} trucks to ${OUT}`);
